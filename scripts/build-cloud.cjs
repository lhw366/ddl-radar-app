'use strict';
const fs = require('node:fs');
const path = require('node:path');
const root = path.join(__dirname, '..');
const configured = JSON.parse(fs.readFileSync(path.join(root, 'config/cloud.public.json'), 'utf8'));
const override = process.env.DDL_SUPABASE_URL || process.env.DDL_SUPABASE_PUBLISHABLE_KEY;
const url = override ? process.env.DDL_SUPABASE_URL || '' : configured.url || '';
const key = override ? process.env.DDL_SUPABASE_PUBLISHABLE_KEY || '' : configured.publishableKey || '';
if (!!url !== !!key) throw new Error('Both public Supabase connection values are required');
if (url && !/^https:\/\/[a-z0-9-]+\.supabase\.co$/.test(url)) throw new Error('Invalid Supabase project HTTPS URL');
if (key && !/^sb_publishable_[A-Za-z0-9_-]+$/.test(key)) throw new Error('Only sb_publishable keys may be embedded');
fs.writeFileSync(path.join(root, 'www/js/cloud-config.js'),
  '// Public connection values; no privileged credentials. Generated by scripts/build-cloud.cjs.\nwindow.DDL_CLOUD_CONFIG = ' +
  JSON.stringify({ url, publishableKey: key }) + ';\n');
require('esbuild').buildSync({ entryPoints: [path.join(__dirname, 'cloud-entry.js')],
  bundle: true, minify: true, platform: 'browser', target: ['chrome89'],
  outfile: path.join(root, 'www/assets/supabase.js'), legalComments: 'external' });
const packages = ['@supabase/supabase-js', '@supabase/auth-js', '@supabase/functions-js',
  '@supabase/postgrest-js', '@supabase/realtime-js', '@supabase/storage-js', '@supabase/phoenix', 'tslib', 'iceberg-js'];
const notices = packages.map(name => {
  const dir = path.join(root, 'node_modules', name);
  const license = fs.readdirSync(dir).find(file => /^licen[cs]e(?:\.|$)/i.test(file));
  if (!license) throw new Error('Missing dependency license: ' + name);
  return name + '\n' + fs.readFileSync(path.join(dir, license), 'utf8');
});
fs.writeFileSync(path.join(root, 'www/assets/supabase.LICENSE.txt'), notices.join('\n\n--------------------\n\n'));
console.log(url ? 'Cloud client built with public project configuration' : 'Cloud client built; project connection pending');
